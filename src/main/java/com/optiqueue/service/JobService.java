package com.optiqueue.service;

import com.optiqueue.config.OptiQueueProperties;
import com.optiqueue.controller.JobRequest;
import com.optiqueue.controller.JobResponse;
import com.optiqueue.domain.Job;
import com.optiqueue.domain.JobStatus;
import com.optiqueue.repository.JobRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import java.util.stream.Collectors;

@Service
public class JobService {

    private static final Logger log = LoggerFactory.getLogger(JobService.class);

    private final JobRepository       jobRepository;
    private final OptiQueueProperties props;

    public JobService(JobRepository jobRepository, OptiQueueProperties props) {
        this.jobRepository = jobRepository;
        this.props = props;
    }

    // ── SUBMIT ────────────────────────────────────────────────────────────

    /**
     * Submits a new job. Returns existing job if idempotency key matches.
     *
     * @return [JobResponse, isNew] — isNew=true if job was created, false if returned existing
     */
    @Transactional
    public JobSubmitResult submitJob(JobRequest request) {

        // ── IDEMPOTENCY CHECK ──────────────────────────────────────────────
        // If client provided an idempotency key, check for existing job first.
        if (request.getIdempotencyKey() != null && !request.getIdempotencyKey().isBlank()) {
            Optional<Job> existing = jobRepository.findByIdempotencyKey(
                request.getIdempotencyKey());

            if (existing.isPresent()) {
                log.info("Idempotent submit: returning existing job {} for key={}",
                    existing.get().getId(), request.getIdempotencyKey());
                // Return the existing job — 200 OK (not 201 Created)
                return new JobSubmitResult(JobResponse.from(existing.get()), false);
            }
        }

        // ── BUILD JOB ENTITY ───────────────────────────────────────────────
        // We set the ID here (not auto-generated by DB) so the client can
        // optionally use this UUID as their idempotency key for future calls.
        UUID jobId = UUID.randomUUID();

        int maxRetries = (request.getMaxRetries() != null)
            ? request.getMaxRetries()
            : props.getRetry().getMaxAttempts();

        Instant deadline = (request.getDeadlineEpochMs() != null)
            ? Instant.ofEpochMilli(request.getDeadlineEpochMs())
            : null;

        String idempotencyKey = (request.getIdempotencyKey() != null
                                 && !request.getIdempotencyKey().isBlank())
            ? request.getIdempotencyKey()
            : jobId.toString(); // Use job ID as default idempotency key

        Job job = Job.builder()
            .id(jobId)
            .idempotencyKey(idempotencyKey)
            .jobType(request.getJobType())
            .payload(request.getPayload())
            .priority(request.getPriority())
            .deadline(deadline)
            .status(JobStatus.PENDING)
            .retryCount(0)
            .maxRetries(maxRetries)
            .isDeadLetter(false)
            .build();

        // @PrePersist sets createdAt and updatedAt before the INSERT
        Job saved = jobRepository.save(job);
        log.info("Job submitted: id={}, type={}, priority={}, idempotencyKey={}",
            saved.getId(), saved.getJobType(), saved.getPriority(), saved.getIdempotencyKey());

        return new JobSubmitResult(JobResponse.from(saved), true);
    }

    // ── GET STATUS ────────────────────────────────────────────────────────

    @Transactional(readOnly = true)
    public Optional<JobResponse> getJob(UUID id) {
        return jobRepository.findById(id).map(JobResponse::from);
    }

    // ── FIND BY IDEMPOTENCY KEY ───────────────────────────────────────────

    /**
     * Looks up a job by its idempotency key.
     * Used by GET /api/jobs?idempotencyKey=... so clients can re-fetch
     * their job using the key they submitted — without needing the UUID.
     *
     * This is the client-facing idempotency story:
     *   1. Client generates key: "order-123-welcome-email"
     *   2. Client submits POST /api/jobs with that key → gets back UUID + 201
     *   3. Client's network drops → client doesn't know if it was received
     *   4. Client re-submits with same key → gets back same job + 200 OK
     *   5. If client lost the UUID too: GET /api/jobs?idempotencyKey=order-123-welcome-email
     */
    @Transactional(readOnly = true)
    public Optional<JobResponse> findByIdempotencyKey(String idempotencyKey) {
        return jobRepository.findByIdempotencyKey(idempotencyKey).map(JobResponse::from);
    }

    // ── GET RESULT ────────────────────────────────────────────────────────

    /**
     * Returns the job result only if status=COMPLETED.
     * Returns empty Optional if job not found OR not yet completed.
     * Controller distinguishes these cases via the Job's status field.
     */
    @Transactional(readOnly = true)
    public Optional<Job> getJobForResult(UUID id) {
        return jobRepository.findById(id);
    }

    // ── CANCEL ────────────────────────────────────────────────────────────

    /**
     * Cancels a job if it is in a cancellable state.
     *
     * Cancellable states: PENDING, IN_PROGRESS
     * Non-cancellable (terminal): COMPLETED, CANCELLED, DEAD_LETTER
     * FAILED/RETRYING: cancellable — stops further retry attempts
     *
     * INTERVIEW Q: "What happens if a worker is mid-execution when cancel is called?"
     * A: We set status=CANCELLED in the DB. The worker, on completion, tries to
     *    call job.complete() which calls transitionTo(COMPLETED). Our state machine
     *    rejects IN_PROGRESS→COMPLETED if status is already CANCELLED in the DB
     *    (because the worker fetches fresh from DB before completing). So the
     *    cancellation wins. For truly atomic cancel-during-execution, you'd need
     *    a distributed cancellation signal (e.g., Redis pub/sub to the worker node).
     *    Production: use a "cancellation token" pattern.
     *
     * @return CancelResult — describes outcome
     */
    @Transactional
    public CancelResult cancelJob(UUID id) {
        Optional<Job> opt = jobRepository.findById(id);
        if (opt.isEmpty()) {
            return CancelResult.NOT_FOUND;
        }

        Job job = opt.get();

        if (job.getStatus() == JobStatus.CANCELLED) {
            return CancelResult.ALREADY_CANCELLED;
        }

        if (job.getStatus() == JobStatus.COMPLETED
            || job.getStatus() == JobStatus.DEAD_LETTER) {
            return CancelResult.TERMINAL_STATE;
        }

        // Force status to CANCELLED regardless of current state.
        // We bypass transitionTo() here because FAILED→CANCELLED isn't in the
        // state machine (we didn't anticipate it), but it's a valid business operation.
        job.setStatus(JobStatus.CANCELLED);
        jobRepository.save(job);

        log.info("Job {} cancelled (was: {})", id, job.getStatus());
        return CancelResult.CANCELLED;
    }

    // ── DEAD LETTER QUEUE & RE-QUEUE ──────────────────────────────────────

    @Transactional(readOnly = true)
    public List<JobResponse> getDeadLetterJobs() {
        return jobRepository.findDeadLetterJobs()
            .stream()
            .map(JobResponse::from)
            .collect(Collectors.toList());
    }

    /**
     * Manually re-queues a DEAD_LETTER job, resetting its retry count and returning it to PENDING.
     */
    @Transactional
    public Optional<JobResponse> retryDeadLetterJob(UUID id) {
        Optional<Job> opt = jobRepository.findById(id);
        if (opt.isEmpty()) {
            return Optional.empty();
        }
        Job job = opt.get();
        job.transitionTo(JobStatus.PENDING);
        job.setRetryCount(0);
        job.setDeadLetter(false);
        job.setLastError(null);
        job.setNextRetryAt(null);
        job.setAssignedWorkerId(null);
        job.setStartedAt(null);
        jobRepository.save(job);
        log.info("Re-queued DEAD_LETTER job {} back to PENDING", id);
        return Optional.of(JobResponse.from(job));
    }

    // ── METRICS & RECENT JOBS ─────────────────────────────────────────────

    @Transactional(readOnly = true)
    public List<JobResponse> getRecentJobs() {
        return jobRepository.findTop50ByOrderByUpdatedAtDesc()
            .stream()
            .map(JobResponse::from)
            .collect(Collectors.toList());
    }

    @Transactional(readOnly = true)
    public QueueMetrics getQueueMetrics() {
        long pending = jobRepository.countByStatus(JobStatus.PENDING);
        long inProgress = jobRepository.countByStatus(JobStatus.IN_PROGRESS);
        long completed = jobRepository.countByStatus(JobStatus.COMPLETED);
        long failed = jobRepository.countByStatus(JobStatus.FAILED);
        long deadLetter = jobRepository.countByStatus(JobStatus.DEAD_LETTER);
        long cancelled = jobRepository.countByStatus(JobStatus.CANCELLED);
        long total = jobRepository.count();
        return new QueueMetrics(pending, inProgress, completed, failed, deadLetter, cancelled, total);
    }

    // ── LIST BY STATUS ────────────────────────────────────────────────────

    @Transactional(readOnly = true)
    public List<JobResponse> getJobsByStatus(JobStatus status) {
        return jobRepository.findByStatus(status)
            .stream()
            .map(JobResponse::from)
            .collect(Collectors.toList());
    }

    // ── RESULT TYPES ──────────────────────────────────────────────────────

    /**
     * Wraps queue status counts for monitoring dashboards.
     */
    public record QueueMetrics(
        long pending,
        long inProgress,
        long completed,
        long failed,
        long deadLetter,
        long cancelled,
        long total
    ) {}

    /**
     * Wraps the job response + a flag indicating whether it was newly created.
     * The controller uses isNew to decide between 201 Created vs 200 OK.
     */
    public record JobSubmitResult(JobResponse response, boolean isNew) {}

    public enum CancelResult {
        CANCELLED,
        NOT_FOUND,
        ALREADY_CANCELLED,
        TERMINAL_STATE
    }
}
